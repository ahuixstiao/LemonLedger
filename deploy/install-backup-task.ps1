# LemonLedger 数据库备份：注册 Windows 计划任务
#
# 用法（在项目目录下，PowerShell 里跑）：
#   powershell -ExecutionPolicy Bypass -File deploy\install-backup-task.ps1
#
# 做的事：
#   1. 在项目根目录生成 run-backup.cmd（纯英文内容，避免中文路径被 cmd 按 GBK 解码搞乱）
#   2. 注册每天 02:30 执行这个 cmd 的计划任务
#   3. 立刻跑一次，确认能出备份文件
#
# 想改时间/删任务（PowerShell）：
#   Set-ScheduledTask -TaskName "LemonLedger 数据库备份" -Trigger (New-ScheduledTaskTrigger -Daily -At 03:00)
#   Unregister-ScheduledTask -TaskName "LemonLedger 数据库备份" -Confirm:$false

param(
  [string]$RepoPath = (Split-Path -Parent $PSScriptRoot),
  [string]$Time = "02:30"
)

$ErrorActionPreference = "Stop"
$taskName = "LemonLedger 数据库备份"

$bash = @(
  "C:\Program Files\Git\bin\bash.exe",
  "C:\Program Files\Git\usr\bin\bash.exe",
  "$env:LOCALAPPDATA\Programs\Git\bin\bash.exe"
) | Where-Object { Test-Path $_ } | Select-Object -First 1

if (-not $bash) {
  throw "没找到 Git 自带的 bash.exe，确认装了 Git for Windows。"
}

$scriptPath = Join-Path $RepoPath "deploy\backup-mysql.sh"
if (-not (Test-Path $scriptPath)) {
  throw "没找到备份脚本：$scriptPath"
}

# 生成 wrapper：内容全 ASCII，路径靠 %USERPROFILE% 展开，避免中文乱码
$repoRelative = $RepoPath
if ($repoRelative.StartsWith($env:USERPROFILE, [System.StringComparison]::OrdinalIgnoreCase)) {
  $repoRelative = "%USERPROFILE%" + $repoRelative.Substring($env:USERPROFILE.Length)
}

$cmdPath = Join-Path $RepoPath "run-backup.cmd"
$cmdContent = @(
  "@echo off",
  "rem LemonLedger daily mysql backup - generated by deploy/install-backup-task.ps1",
  "cd /d `"$repoRelative`"",
  "`"$bash`" -lc `"bash deploy/backup-mysql.sh`"",
  "exit /b %ERRORLEVEL%"
) -join "`r`n"

Set-Content -Path $cmdPath -Value $cmdContent -Encoding ASCII

Write-Host "wrapper : $cmdPath"
Write-Host "bash    : $bash"
Write-Host "repo    : $RepoPath"

$action = New-ScheduledTaskAction -Execute $cmdPath -WorkingDirectory $RepoPath
$trigger = New-ScheduledTaskTrigger -Daily -At $Time
$description = "LemonLedger 每天导出 ledger 库到 backups 目录"
Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Description $description -Force | Out-Null

Write-Host ""
Write-Host "先手动跑一次验证："
Start-ScheduledTask -TaskName $taskName
Start-Sleep -Seconds 25

$backupDir = Join-Path $RepoPath "backups"
$latest = Get-ChildItem $backupDir -Filter "ledger-*.sql.gz" -ErrorAction SilentlyContinue |
  Sort-Object LastWriteTime -Descending | Select-Object -First 1

if ($latest) {
  Write-Host "最新备份：$($latest.Name)（$([math]::Round($latest.Length / 1KB, 1)) KB，$($latest.LastWriteTime)）" -ForegroundColor Green
} else {
  Write-Warning "还没看到备份文件，检查 $backupDir\backup.log"
}

Write-Host ""
Write-Host "完成。每天 $Time 自动备份，保留最近 14 份。" -ForegroundColor Green
